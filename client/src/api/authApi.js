import api from './axiosInstance';

export const authApi = {
  register: (data) => api.post('/auth/register', data),
  login: (data) => api.post('/auth/login', data),
  loginTwoFactor: (challenge, code) => api.post('/auth/login/2fa', { challenge, code }),
  resendTwoFactor: (challenge) => api.post('/auth/login/2fa/resend', { challenge }),
  updateProfile: (data) => api.put('/auth/me/profile', data),
  changePassword: (data) => api.put('/auth/me/password', data),
  getSessions: () => api.get('/auth/me/sessions'),
  revokeSession: (id) => api.delete(`/auth/me/sessions/${id}`),
  revokeOtherSessions: () => api.delete('/auth/me/sessions'),
  sendTwoFactorCode: () => api.post('/auth/me/2fa/send-code'),
  enableTwoFactor: (challenge, code) => api.post('/auth/me/2fa/enable', { challenge, code }),
  disableTwoFactor: (password) => api.post('/auth/me/2fa/disable', { password }),
  updatePrivacy: (data) => api.put('/auth/me/privacy', data),
  googleLogin: (token) => api.post('/auth/google', { token }),
  logout: () => api.post('/auth/logout'),
  refresh: () => api.post('/auth/refresh'),
  getMe: () => api.get('/auth/me'),
  updateAvatar: (avatar_url) => api.put('/auth/me/avatar', { avatar_url }),
  forgotPassword: (email) => api.post('/auth/forgot-password', { email }),
  resetPassword: (token, password) => api.post(`/auth/reset-password/${token}`, { password }),
  verifyEmail: (token) => api.get(`/auth/verify-email/${token}`),
  resendVerification: (email) => api.post('/auth/resend-verification', { email }),
};
